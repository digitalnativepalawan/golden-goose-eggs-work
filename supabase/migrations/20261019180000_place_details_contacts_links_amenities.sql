-- ═══════════════════════════════════════════════════════════════════════
-- Places, step 1: the practical block a real listing needs
-- ═══════════════════════════════════════════════════════════════════════
--
-- Why
--   A resort is currently a map pin with a name, one photo and a description.
--   There is nowhere to put a phone number, an address, a Facebook page, or the
--   fact that the rooms have aircon and the kitchen does breakfast. The admin
--   had exactly one place to send that information: the Google Business Profile
--   field, and all 33 listings have it empty.
--
--   Detail belongs in related tables, not in forty more columns on
--   destinations: a place has zero or many phones, zero or many links, and a
--   fixed vocabulary of facilities that we want to filter on later ("has pool",
--   "pet friendly"). One row per place for the practical block, and lists for
--   the rest.
--
-- Shape
--   place_details      one row per place  — address, hours, prices, policies
--   place_contacts     many per place     — phones, email, Viber, WhatsApp
--   place_links        many per place     — website, Facebook, Instagram, booking
--   amenities          fixed vocabulary   — the things a place can have
--   place_amenities    many per place     — which of them this place has
--
-- Access
--   Public read, admin-only write, exactly like the other content tables after
--   the lockdown migration. Visitors read listings; only an admin edits them.
--   Owner-submitted drafts are a later step, not this one.
--
-- Safe to run more than once. Nothing is dropped and no existing row changes.
-- ═══════════════════════════════════════════════════════════════════════

-- ── 1. The practical block ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.place_details (
  place_id        bigint PRIMARY KEY REFERENCES public.destinations(id) ON DELETE CASCADE,
  address         text,
  plus_code       text,
  landmark        text,
  how_to_get      text,
  hours           text,
  best_time       text,
  price_range     text,          -- ₱ / ₱₱ / ₱₱₱
  price_from      numeric,
  price_unit      text,          -- night, person, plate, trip
  entrance_fee    text,
  check_in        text,
  check_out       text,
  payment_methods text[] DEFAULT '{}',
  languages       text[] DEFAULT '{}',
  policies        text,
  accessibility   text,
  updated_at      timestamptz DEFAULT now(),
  verified_at     timestamptz,
  verified_by     text,
  source          text
);

-- ── 2. Phones, mailboxes and messaging ──────────────────────────────────
CREATE TABLE IF NOT EXISTS public.place_contacts (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  place_id   bigint NOT NULL REFERENCES public.destinations(id) ON DELETE CASCADE,
  kind       text NOT NULL,      -- phone, mobile, whatsapp, viber, email, messenger, other
  value      text NOT NULL,
  label      text,               -- Front desk, Reservations, Boat operator
  sort_order integer DEFAULT 0
);
CREATE INDEX IF NOT EXISTS place_contacts_place_idx ON public.place_contacts (place_id, sort_order);

-- ── 3. Where else this place lives online ───────────────────────────────
CREATE TABLE IF NOT EXISTS public.place_links (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  place_id   bigint NOT NULL REFERENCES public.destinations(id) ON DELETE CASCADE,
  kind       text NOT NULL,      -- website, facebook, instagram, tiktok, youtube, google, booking, agoda, airbnb, messenger, other
  url        text NOT NULL,
  label      text,
  sort_order integer DEFAULT 0
);
CREATE INDEX IF NOT EXISTS place_links_place_idx ON public.place_links (place_id, sort_order);

-- ── 4. The amenity vocabulary ───────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.amenities (
  key        text PRIMARY KEY,
  label      text NOT NULL,
  icon       text,               -- a Lucide name from the shared icon set
  grp        text,               -- Room, Facilities, Food, Activities, Services, Access, Policies
  sort_order integer DEFAULT 0
);

-- ── 5. Which of them this place has ─────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.place_amenities (
  place_id    bigint NOT NULL REFERENCES public.destinations(id) ON DELETE CASCADE,
  amenity_key text   NOT NULL REFERENCES public.amenities(key) ON DELETE CASCADE,
  note        text,
  PRIMARY KEY (place_id, amenity_key)
);

-- ── 6. Public read, admin write ─────────────────────────────────────────
DO $$
DECLARE
  t text;
  p record;
  tables text[] := ARRAY['place_details','place_contacts','place_links','amenities','place_amenities'];
BEGIN
  FOREACH t IN ARRAY tables LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    FOR p IN SELECT policyname FROM pg_policies WHERE schemaname='public' AND tablename=t LOOP
      EXECUTE format('DROP POLICY %I ON public.%I', p.policyname, t);
    END LOOP;
    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO anon, authenticated USING (true)', 'Public read '||t, t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL TO authenticated USING (public.has_role(auth.uid(), ''admin'')) WITH CHECK (public.has_role(auth.uid(), ''admin''))', 'Admins write '||t, t);
    EXECUTE format('REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.%I FROM anon', t);
    EXECUTE format('GRANT SELECT ON public.%I TO anon, authenticated', t);
    EXECUTE format('GRANT INSERT, UPDATE, DELETE ON public.%I TO authenticated', t);
  END LOOP;
END $$;

DO $$
DECLARE s text;
BEGIN
  FOR s IN SELECT sequence_name FROM information_schema.sequences
    WHERE sequence_schema='public' AND sequence_name IN ('place_contacts_id_seq','place_links_id_seq')
  LOOP
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE public.%I TO authenticated', s);
  END LOOP;
END $$;

