-- ═══════════════════════════════════════════════════════════════════════
-- Partner round 2: hunt clues, event descriptions, tribe chat, place tips
-- ═══════════════════════════════════════════════════════════════════════
--
-- Why
--   Four partner requests need somewhere to live before the interface can
--   offer them: a clue per hunting spot unlocked by GPS, the organiser's own
--   description on an event, a description plus a chat on a tribe, and
--   visitor tips on a place in place of the retired "Ask tala".
--
-- What this does (safe to run more than once)
--   1. destinations gains `clue` (the riddle) and `hunt_spot` (is this one of
--      the hidden hunting spots).
--   2. events gains `description` — the organiser's own words.
--   3. tribes gains `description`, plus `device_id`/`display_name` so a
--      visitor-created tribe is a real shared row instead of living only on
--      the phone that made it. Insert is opened to visitors with the same
--      length guards the other visitor-written tables use (tribe_members,
--      event_interest, today_interest). Delete stays admin-only: a visitor
--      cannot remove a tribe, theirs or anyone else's.
--   4. place_tips and tribe_messages are new visitor-written tables: public
--      read, insert guarded by length. No delete, matching the loose-but-
--      guarded model the rest of the visitor content already uses.
--
-- Nothing is dropped, no row is modified, no existing policy is weakened.
-- ═══════════════════════════════════════════════════════════════════════

-- 1. The Hunt: a clue on the spot itself.
ALTER TABLE public.destinations ADD COLUMN IF NOT EXISTS clue text;
ALTER TABLE public.destinations ADD COLUMN IF NOT EXISTS hunt_spot boolean NOT NULL DEFAULT false;

-- 2. Events: what the organiser wrote.
ALTER TABLE public.events ADD COLUMN IF NOT EXISTS description text;

-- 3. Tribes: a description, and an author when a visitor creates one.
ALTER TABLE public.tribes ADD COLUMN IF NOT EXISTS description text;
ALTER TABLE public.tribes ADD COLUMN IF NOT EXISTS device_id text;
ALTER TABLE public.tribes ADD COLUMN IF NOT EXISTS display_name text;

DROP POLICY IF EXISTS tribes_member_create ON public.tribes;
CREATE POLICY tribes_member_create ON public.tribes
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    device_id IS NOT NULL
    AND char_length(device_id) BETWEEN 4 AND 64
    AND char_length(coalesce(title,'')) BETWEEN 2 AND 60
    AND char_length(coalesce(display_name,'')) <= 40
  );
GRANT INSERT ON public.tribes TO anon, authenticated;

-- 4a. Tips left on a place. place_key is text so it can cover a directory
--     destination ('d:7') and an open-street-map place ('np:osm-123') alike.
CREATE TABLE IF NOT EXISTS public.place_tips (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  place_key text NOT NULL,
  device_id text NOT NULL,
  display_name text,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS place_tips_place_key_idx ON public.place_tips (place_key, created_at DESC);
ALTER TABLE public.place_tips ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS place_tips_read ON public.place_tips;
CREATE POLICY place_tips_read ON public.place_tips
  FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS place_tips_add ON public.place_tips;
CREATE POLICY place_tips_add ON public.place_tips
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    char_length(place_key) BETWEEN 1 AND 80
    AND char_length(device_id) BETWEEN 4 AND 64
    AND char_length(body) BETWEEN 3 AND 600
    AND char_length(coalesce(display_name,'')) <= 40
  );
GRANT SELECT, INSERT ON public.place_tips TO anon, authenticated;

-- 4b. One chat per tribe.
CREATE TABLE IF NOT EXISTS public.tribe_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tribe_id uuid NOT NULL,
  device_id text NOT NULL,
  display_name text,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS tribe_messages_tribe_idx ON public.tribe_messages (tribe_id, created_at);
ALTER TABLE public.tribe_messages ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tribe_messages_read ON public.tribe_messages;
CREATE POLICY tribe_messages_read ON public.tribe_messages
  FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS tribe_messages_add ON public.tribe_messages;
CREATE POLICY tribe_messages_add ON public.tribe_messages
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    char_length(device_id) BETWEEN 4 AND 64
    AND char_length(body) BETWEEN 1 AND 600
    AND char_length(coalesce(display_name,'')) <= 40
  );
GRANT SELECT, INSERT ON public.tribe_messages TO anon, authenticated;

-- Identity columns need sequence access for the new tables.
DO $$
DECLARE s text;
BEGIN
  FOR s IN
    SELECT sequence_name FROM information_schema.sequences
     WHERE sequence_schema = 'public'
       AND sequence_name IN ('place_tips_id_seq','tribe_messages_id_seq','tribes_id_seq')
  LOOP
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE public.%I TO anon, authenticated', s);
  END LOOP;
END $$;
