-- ═══════════════════════════════════════════════════════════════════════
-- The Hunt: riddles as their own thing
-- ═══════════════════════════════════════════════════════════════════════
--
-- Why a separate table and not the place directory
--   A hunting spot is meant to be found, not listed. If these nine were rows in
--   destinations they would appear as ordinary pins in Explore and give
--   themselves away before anyone read a line of the verse. They also carry
--   things a place does not: a title of their own, a difficulty, and a coordinate
--   that is the answer rather than an address.
--
--   So: their own table. Public read, admin write, same rule as every other
--   content table. The partner edits these in the Backoffice and adds more as he
--   writes them.
--
-- Image
--   image_url is deliberately nullable. Until a photo is uploaded the Hunt shows
--   a neutral placeholder rather than a broken image, so the nine can go live
--   now and get pictures later.
--
-- Safe to run more than once: keyed on slug, so re-running updates the wording
-- instead of duplicating the riddle.
-- ═══════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.hunt_riddles (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug        text UNIQUE NOT NULL,
  title       text NOT NULL,
  verse       text NOT NULL,
  lat         double precision NOT NULL,
  lng         double precision NOT NULL,
  difficulty  text,
  image_url   text,
  hint        text,
  active      boolean NOT NULL DEFAULT true,
  sort_order  integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.hunt_riddles ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE p record;
BEGIN
  FOR p IN SELECT policyname FROM pg_policies WHERE schemaname='public' AND tablename='hunt_riddles' LOOP
    EXECUTE format('DROP POLICY %I ON public.hunt_riddles', p.policyname);
  END LOOP;
END $$;

CREATE POLICY "Public read hunt_riddles" ON public.hunt_riddles
  FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Admins write hunt_riddles" ON public.hunt_riddles
  FOR ALL TO authenticated
  USING (public.has_role(auth.uid(), 'admin'))
  WITH CHECK (public.has_role(auth.uid(), 'admin'));

REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.hunt_riddles FROM anon;
GRANT SELECT ON public.hunt_riddles TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.hunt_riddles TO authenticated;

DO $$
DECLARE s text;
BEGIN
  FOR s IN SELECT sequence_name FROM information_schema.sequences
    WHERE sequence_schema='public' AND sequence_name = 'hunt_riddles_id_seq'
  LOOP EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE public.%I TO authenticated', s); END LOOP;
END $$;

