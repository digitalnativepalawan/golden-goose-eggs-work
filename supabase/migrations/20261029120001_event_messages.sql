-- Event chat: one room per event, modelled on tribe_messages.
--
-- Events were not getting "a chat" from James, so both tribes and events get a
-- visitor-written room, and events get the member side of the join as well.

CREATE TABLE IF NOT EXISTS public.event_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id text NOT NULL,
  device_id text NOT NULL,
  display_name text NOT NULL,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS event_messages_event_idx ON public.event_messages (event_id, created_at);

ALTER TABLE public.event_messages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS event_messages_read ON public.event_messages;
CREATE POLICY event_messages_read ON public.event_messages
  FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS event_messages_add ON public.event_messages;
CREATE POLICY event_messages_add ON public.event_messages
  FOR INSERT TO anon, authenticated WITH CHECK (true);

GRANT SELECT, INSERT ON public.event_messages TO anon, authenticated;
REVOKE SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON public.event_messages FROM anon;

-- The generated sequence is not covered by the grant above, so grant it too.
DO $$
DECLARE s text;
BEGIN
  FOR s IN SELECT sequence_name FROM information_schema.sequences
    WHERE sequence_schema='public' AND sequence_name='event_messages_id_seq'
  LOOP
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE public.%I TO anon, authenticated', s);
  END LOOP;
END $$;
